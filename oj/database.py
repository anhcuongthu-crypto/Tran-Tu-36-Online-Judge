
import os
import sqlite3
from pathlib import Path


def is_postgres(path=None):
    value = path or os.getenv('DATABASE_URL', '')
    return value.startswith((
        'postgres://',
        'postgresql://',
        'postgresql+psycopg://'
    ))


class PostgresConnection:
    def __init__(self, path):
        import psycopg
        from psycopg.rows import dict_row

        self.db = psycopg.connect(path, row_factory=dict_row)

    def execute(self, sql, params=()):
        sql = sql.replace('?', '%s')
        return self.db.execute(sql, params)

    def executemany(self, sql, seq):
        sql = sql.replace('?', '%s')
        return self.db.executemany(sql, seq)

    def __enter__(self):
        self.db.__enter__()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self.db.__exit__(exc_type, exc_value, traceback)

    def close(self):
        self.db.close()

    def commit(self):
        self.db.commit()

    def rollback(self):
        self.db.rollback()


def connect(path=None):
    path = path or os.getenv(
        'DATABASE_URL',
        'instance/online_judge.sqlite3'
    )

    if is_postgres(path):
        return PostgresConnection(path)

    Path(path).parent.mkdir(parents=True, exist_ok=True)
    db = sqlite3.connect(path, timeout=20)
    db.row_factory = sqlite3.Row
    db.execute('PRAGMA foreign_keys=ON')
    return db


def init_db(path=None):
    path = path or os.getenv(
        'DATABASE_URL',
        'instance/online_judge.sqlite3'
    )

    if is_postgres(path):
        _init_postgres(path)
    else:
        _init_sqlite(path)


